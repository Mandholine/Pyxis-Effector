    function getNodeTitle(nodeOrType) {
        if (!nodeOrType) return "";
        let typeOrTitle = typeof nodeOrType === "string" ? nodeOrType : (nodeOrType.title || nodeOrType.type || "");
        let clean = String(typeOrTitle).trim();
        if (clean.includes("/")) {
            const parts = clean.split("/");
            clean = parts[parts.length - 1];
        }
        if (currentLanguage === "en") {
            const rev = REVERSE_TITLES[clean] || REVERSE_TITLES[clean.toLowerCase()];
            if (rev) return rev;
            return clean;
        }
        const key = "nodes.titles." + clean;
        const translated = t(key, null, null);
        if (translated && translated !== key) return translated;
        const enKey = REVERSE_TITLES[clean] || REVERSE_TITLES[clean.toLowerCase()];
        if (enKey) {
            const tr = t("nodes.titles." + enKey, null, clean);
            if (tr) return tr;
        }
        return clean;
    }

    function translateSlot(slotText) {
        if (!slotText || typeof slotText !== "string" || slotText.trim() === "") return slotText;
        const clean = slotText.trim();
        const hasColon = clean.endsWith(":");
        const base = hasColon ? clean.slice(0, -1).trim() : clean;
        const suffix = hasColon ? ":" : "";

        if (currentLanguage === "en") {
            const mEntrada = base.match(/^Entrada\s*(\d+)$/i);
            if (mEntrada) return "In " + mEntrada[1] + suffix;
            const mSalida = base.match(/^Salida\s*(\d+)$/i);
            if (mSalida) return "Out " + mSalida[1] + suffix;
            const mValor = base.match(/^Valor\s*(\d+)$/i);
            if (mValor) return "Value " + mValor[1] + suffix;
            const rev = REVERSE_SLOTS[base] || REVERSE_SLOTS[base.toLowerCase()] || REVERSE_SLOTS[clean] || REVERSE_SLOTS[clean.toLowerCase()];
            if (rev) return rev + (hasColon && !rev.endsWith(":") ? ":" : "");
            return slotText;
        }

        const key = "nodes.slots." + base;
        let translated = t(key, null, null);
        if (!translated || translated === key) {
            const keyFull = "nodes.slots." + clean;
            translated = t(keyFull, null, null);
            if (translated && translated !== keyFull) return translated;
        }
        if (translated && translated !== key) return translated + suffix;

        const enKey = REVERSE_SLOTS[base] || REVERSE_SLOTS[base.toLowerCase()];
        if (enKey) {
            const tr = t("nodes.slots." + enKey, null, null);
            if (tr && tr !== ("nodes.slots." + enKey)) return tr + suffix;
        }

        // Smart regex fallback for numbered slots in Spanish
        const mIn = base.match(/^(?:In|Input)\s*(\d+)$/i);
        if (mIn) return t("nodes.slots.In", null, "Entrada") + " " + mIn[1] + suffix;

        const mOut = base.match(/^(?:Out|Output)\s*(\d+)$/i);
        if (mOut) return t("nodes.slots.Out", null, "Salida") + " " + mOut[1] + suffix;

        const mV = base.match(/^V\s*(\d+)$/i);
        if (mV) return "V" + mV[1] + suffix;

        const mTag = base.match(/^(?:Tag|TAG)\s*(\d+)$/i);
        if (mTag) return "TAG " + mTag[1] + suffix;

        const mCol = base.match(/^Color\s*(\d+)$/i);
        if (mCol) return "Color " + mCol[1] + suffix;

        return slotText;
    }

