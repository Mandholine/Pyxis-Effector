static void ass_path(FILE *fout, potrace_curve_t *curve, double width, double height) {
    int m = curve->n;
    if (m == 0) return;

    double cx = width / 2.0;
    double cy = height / 2.0;

    /* Invert Y coordinate so it matches screen canvas (Y grows downward in ASS) */
    dpoint_t *c = curve->c[m - 1];
    long start_x = (long)round(c[2].x - cx);
    long start_y = (long)round((height - c[2].y) - cy);
    fprintf(fout, "m %ld %ld ", start_x, start_y);

    for (int i = 0; i < m; i++) {
        c = curve->c[i];
        if (curve->tag[i] == POTRACE_CORNER) {
            long p1x = (long)round(c[1].x - cx);
            long p1y = (long)round((height - c[1].y) - cy);
            long p2x = (long)round(c[2].x - cx);
            long p2y = (long)round((height - c[2].y) - cy);
            fprintf(fout, "l %ld %ld l %ld %ld ", p1x, p1y, p2x, p2y);
        } else if (curve->tag[i] == POTRACE_CURVETO) {
            long p0x = (long)round(c[0].x - cx);
            long p0y = (long)round((height - c[0].y) - cy);
            long p1x = (long)round(c[1].x - cx);
            long p1y = (long)round((height - c[1].y) - cy);
            long p2x = (long)round(c[2].x - cx);
            long p2y = (long)round((height - c[2].y) - cy);
            fprintf(fout, "b %ld %ld %ld %ld %ld %ld ", p0x, p0y, p1x, p1y, p2x, p2y);
        }
    }
}

static void write_ass_paths_rec(FILE *fout, potrace_path_t *tree, double width, double height) {
    for (potrace_path_t *p = tree; p; p = p->sibling) {
        ass_path(fout, &p->curve, width, height);
        for (potrace_path_t *q = p->childlist; q; q = q->sibling) {
            ass_path(fout, &q->curve, width, height);
        }
        for (potrace_path_t *q = p->childlist; q; q = q->sibling) {
            write_ass_paths_rec(fout, q->childlist, width, height);
        }
    }
}

int page_ass(FILE *fout, potrace_path_t *plist, imginfo_t *imginfo) {
    double w = imginfo->trans.bb[0];
    double h = imginfo->trans.bb[1];

    /* Output complete Aegisub ASS subtitle document */
    fprintf(fout, "[Script Info]\n");
    fprintf(fout, "; Script generated by Native Potrace for Aegisub\n");
    fprintf(fout, "Title: Potrace ASS Shape\n");
    fprintf(fout, "ScriptType: v4.00+\n");
    fprintf(fout, "WrapStyle: 0\n");
    fprintf(fout, "ScaledBorderAndShadow: yes\n");
    fprintf(fout, "PlayResX: 1920\n");
    fprintf(fout, "PlayResY: 1080\n\n");

    fprintf(fout, "[V4+ Styles]\n");
    fprintf(fout, "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n");
    fprintf(fout, "Style: Default,Arial,20,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,0,5,10,10,10,1\n\n");

    fprintf(fout, "[Events]\n");
    fprintf(fout, "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n");
    fprintf(fout, "Dialogue: 0,0:00:00.00,0:00:10.00,Default,,0,0,0,,{\\an5\\pos(960,540)\\p1}");

    write_ass_paths_rec(fout, plist, w, h);

    fprintf(fout, "{\\p0}\n");
    fflush(fout);
    return 0;
}
